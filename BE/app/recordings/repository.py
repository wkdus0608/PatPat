from collections.abc import AsyncIterator
from typing import BinaryIO, Protocol

from app.recordings.models import Recording, RecordingReference


class RecordingRepository(Protocol):
    """Every query is teacher-scoped. Deleted recordings are excluded."""

    async def create(self, *, teacher_id: str, recording: Recording) -> Recording:
        ...

    async def list(self, *, teacher_id: str) -> list[Recording]:
        ...

    async def get(self, *, teacher_id: str, recording_id: str) -> Recording | None:
        ...

    async def get_reference(
        self, *, teacher_id: str, recording_id: str
    ) -> RecordingReference | None:
        ...

    async def mark_deleted(self, *, teacher_id: str, recording_id: str) -> None:
        """Exclude from new requests; keep existing diary evidence snapshots."""
        ...


class PrivateAudioStorage(Protocol):
    """Keys are generated by the server and never returned in API responses."""

    async def save(
        self, *, teacher_id: str, recording_id: str, source: BinaryIO,
        content_type: str,
    ) -> None:
        """Validate actual format/size and store in a private server area."""
        ...

    async def open(
        self, *, teacher_id: str, recording_id: str
    ) -> AsyncIterator[bytes]:
        """Release storage handles when iteration finishes or is cancelled."""
        ...

    async def delete(self, *, teacher_id: str, recording_id: str) -> None:
        ...
